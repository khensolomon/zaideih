/**
 * D1 helpers for tools/d1.mjs: the schema as one statement list, the reset
 * script, and reading wrangler's JSON output. Pure functions, so they are
 * tested without Cloudflare.
 */

export class D1Error extends Error {}

/** Tables kept by a reset: Cloudflare's own (_cf_*) and SQLite's (sqlite_*). */
export const isSystemTable = (name) => name.startsWith("_cf_") || name.startsWith("sqlite_");

/** The schema file without comments or blank lines, as one SQL text. */
export function schemaSql(text) {
	const sql = text
		.split("\n")
		.map((line) => line.replace(/--.*$/, "").trimEnd())
		.filter((line) => line.trim())
		.join("\n");
	if (!/CREATE TABLE/i.test(sql)) throw new D1Error("the schema file has no CREATE TABLE statement");
	return `${sql}\n`;
}

/** Table names the schema creates, in order. */
export function schemaTables(text) {
	return [...schemaSql(text).matchAll(/CREATE TABLE IF NOT EXISTS\s+([A-Za-z_][A-Za-z0-9_]*)/gi)].map((m) => m[1]);
}

const sqlText = (s) => `'${String(s).replace(/'/g, "''")}'`;

/**
 * The reset script: drops every existing table (except system tables),
 * creates the schema, loads the track paths and, when given, puts the
 * saved play counts back. One file, run as one D1 import, so it either
 * completes or leaves the database as it was.
 */
export function resetSql({ tables, schema, tracks, plays = null }) {
	const drop = tables.filter((t) => !isSystemTable(t));
	const out = [
		"-- Generated by tools/d1.mjs reset. Do not edit.",
		...drop.map((t) => `DROP TABLE IF EXISTS "${t.replace(/"/g, '""')}";`),
		schemaSql(schema).trimEnd(),
		tracks.trimEnd(),
	];
	if (plays?.length) {
		for (let i = 0; i < plays.length; i += 500) {
			const rows = plays.slice(i, i + 500).map(({ track_id: id, day, n }) => {
				if (!Number.isSafeInteger(id) || !/^\d{4}-\d{2}-\d{2}$/.test(day) || !Number.isSafeInteger(n)) throw new D1Error(`unexpected plays row ${JSON.stringify({ id, day, n })}`);
				return `(${id}, ${sqlText(day)}, ${n})`;
			});
			out.push(`INSERT INTO plays (track_id, day, n) VALUES\n${rows.join(",\n")};`);
		}
	}
	return `${out.join("\n")}\n`;
}

/**
 * The rows of the first result in `wrangler d1 execute --json` output.
 * Wrangler prints a JSON array of results; anything else is an error with
 * the text it printed.
 */
export function wranglerRows(stdout) {
	// Warnings come first ("▲ [WARNING] …"); the JSON starts on its own line with "[" and "{" or "]".
	const start = stdout.search(/^\[\s*[{\]]/m);
	if (start < 0) throw new D1Error(`wrangler did not print JSON:\n${stdout.trim().slice(0, 800)}`);
	let parsed;
	try {
		parsed = JSON.parse(stdout.slice(start));
	} catch {
		throw new D1Error(`wrangler did not print JSON:\n${stdout.trim().slice(0, 800)}`);
	}
	if (!Array.isArray(parsed) || !parsed[0]) throw new D1Error(`unexpected wrangler output: ${stdout.trim().slice(0, 400)}`);
	if (parsed[0].success === false) throw new D1Error(`D1 query failed: ${JSON.stringify(parsed[0].error ?? parsed[0])}`);
	return parsed[0].results ?? [];
}

/** Tables that cannot be rebuilt from git: personal libraries (docs/library.md). */
export const LIBRARY_TABLES = Object.freeze(["members", "uploads"]);

/**
 * Why a reset must not go ahead, or null: it would lose personal libraries
 * (`counts`: rows per table) unless `dropLibrary` was chosen.
 */
export function libraryGuard(counts, dropLibrary) {
	const held = LIBRARY_TABLES.filter((t) => (counts[t] ?? 0) > 0);
	if (!held.length || dropLibrary) return null;
	return `${held.map((t) => `${t} holds ${counts[t]} row${counts[t] === 1 ? "" : "s"}`).join(" and ")}. Personal libraries cannot be rebuilt from git, and their files would stay in R2 (users/…) without an owner. Use "schema --apply" to add what is missing instead, or re-run with --drop-library to lose them.`;
}
