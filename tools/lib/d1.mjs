/**
 * D1 helpers for tools/d1.mjs: the schema as one statement list, the reset
 * script, and reading wrangler's JSON output. Pure functions, so they are
 * tested without Cloudflare.
 */

export class D1Error extends Error {}

/** Tables kept by a reset: Cloudflare's own (_cf_*) and SQLite's (sqlite_*). */
export const isSystemTable = (name) => name.startsWith("_cf_") || name.startsWith("sqlite_");

/** SQL without comments or blank lines ("--" must not appear inside string literals). */
const stripSql = (text) => text
	.split("\n")
	.map((line) => line.replace(/--.*$/, "").trimEnd())
	.filter((line) => line.trim())
	.join("\n");

/** The schema file without comments or blank lines, as one SQL text. */
export function schemaSql(text) {
	const sql = stripSql(text);
	if (!/CREATE TABLE/i.test(sql)) throw new D1Error("the schema file has no CREATE TABLE statement");
	return `${sql}\n`;
}

/* ------------------------------------------------------------ migrations ---- */

/** worker/media/migrations/<NNNN>-<name>.sql, run in name order. */
export const MIGRATION_NAME = /^\d{4}-[a-z0-9-]+\.sql$/;
const MIGRATIONS_TABLE = "CREATE TABLE IF NOT EXISTS schema_migrations (name TEXT PRIMARY KEY, applied_at INTEGER NOT NULL);";

/**
 * What `tools/d1.mjs schema` does about migrations: `run` the ones the
 * database has not had, in order; or, for a database the schema is about to
 * create (it has no `members` table yet), `record` them as run without
 * running them, since schema.sql already has their result. Refuses a
 * database that has had migrations this checkout does not know.
 */
export function migrationPlan({ tables, applied, migrations }) {
	for (const name of migrations) if (!MIGRATION_NAME.test(name)) throw new D1Error(`migration file name ${name} must look like 0001-what-it-does.sql`);
	const known = new Set(migrations);
	const unknown = applied.filter((n) => !known.has(n));
	if (unknown.length) throw new D1Error(`the database has had migrations this checkout does not have (${unknown.join(", ")}); update the checkout first`);
	const pending = [...migrations].sort().filter((n) => !applied.includes(n));
	return tables.includes("members") ? { run: pending, record: [] } : { run: [], record: pending };
}

const recordSql = (names, nowSeconds) => names.length
	? `${MIGRATIONS_TABLE}\n${names.map((n) => `INSERT INTO schema_migrations (name, applied_at) VALUES (${sqlText(n)}, ${nowSeconds});`).join("\n")}\n`
	: "";

/** One migration and its record, sent as one import, so it either completes or changes nothing. */
export function migrationSql(name, text, nowSeconds) {
	const sql = stripSql(text);
	if (!sql) throw new D1Error(`migration ${name} is empty`);
	return `${sql}\n${recordSql([name], nowSeconds)}`;
}

/** Records migrations as run (a database created from schema.sql already has their result). */
export const recordMigrationsSql = (names, nowSeconds) => recordSql(names, nowSeconds);

/** Table names the schema creates, in order. */
export function schemaTables(text) {
	return [...schemaSql(text).matchAll(/CREATE TABLE IF NOT EXISTS\s+([A-Za-z_][A-Za-z0-9_]*)/gi)].map((m) => m[1]);
}

const sqlText = (s) => `'${String(s).replace(/'/g, "''")}'`;

/**
 * The reset script: drops every existing table (except system tables),
 * creates the schema, loads the track paths and, when given, puts the
 * saved play counts back. One file, run as one D1 import, so it either
 * completes or leaves the database as it was.
 */
export function resetSql({ tables, schema, tracks, plays = null, migrations = [], nowSeconds = Math.floor(Date.now() / 1000) }) {
	const drop = tables.filter((t) => !isSystemTable(t));
	const out = [
		"-- Generated by tools/d1.mjs reset. Do not edit.",
		...drop.map((t) => `DROP TABLE IF EXISTS "${t.replace(/"/g, '""')}";`),
		schemaSql(schema).trimEnd(),
		recordSql(migrations, nowSeconds).trimEnd(),
		tracks.trimEnd(),
	];
	if (plays?.length) {
		for (let i = 0; i < plays.length; i += 500) {
			const rows = plays.slice(i, i + 500).map(({ track_id: id, day, n }) => {
				if (!Number.isSafeInteger(id) || !/^\d{4}-\d{2}-\d{2}$/.test(day) || !Number.isSafeInteger(n)) throw new D1Error(`unexpected plays row ${JSON.stringify({ id, day, n })}`);
				return `(${id}, ${sqlText(day)}, ${n})`;
			});
			out.push(`INSERT INTO plays (track_id, day, n) VALUES\n${rows.join(",\n")};`);
		}
	}
	return `${out.join("\n")}\n`;
}

/**
 * The rows of the first result in `wrangler d1 execute --json` output.
 * Wrangler prints a JSON array of results; anything else is an error with
 * the text it printed.
 */
export function wranglerRows(stdout) {
	// Warnings come first ("▲ [WARNING] …"); the JSON starts on its own line with "[" and "{" or "]".
	const start = stdout.search(/^\[\s*[{\]]/m);
	if (start < 0) throw new D1Error(`wrangler did not print JSON:\n${stdout.trim().slice(0, 800)}`);
	let parsed;
	try {
		parsed = JSON.parse(stdout.slice(start));
	} catch {
		throw new D1Error(`wrangler did not print JSON:\n${stdout.trim().slice(0, 800)}`);
	}
	if (!Array.isArray(parsed) || !parsed[0]) throw new D1Error(`unexpected wrangler output: ${stdout.trim().slice(0, 400)}`);
	if (parsed[0].success === false) throw new D1Error(`D1 query failed: ${JSON.stringify(parsed[0].error ?? parsed[0])}`);
	return parsed[0].results ?? [];
}

/**
 * The lyrics backup (`tools/d1.mjs lyrics`, docs/lyrics.md): what is shown,
 * and every version, per song and language (lang "" the original), which
 * recordings share another's lyrics, and each recording's own timing of a
 * shared text, as read from D1. Member ids only, no names or emails.
 * Throws when a shown version has no row in the versions (a broken read).
 */
export function lyricsBackup(lyrics, versions, exportedAt, { links = [], times = [] } = {}) {
	const key = (r) => `${r.track}/${r.lang ?? ""}:${r.version}`;
	const kept = new Set(versions.map(key));
	const lost = lyrics.filter((l) => !kept.has(key(l)));
	if (lost.length) throw new D1Error(`the versions read do not include the shown lyrics of song(s) ${lost.slice(0, 10).map((l) => l.track).join(", ")}; nothing was written`);
	return {
		format: "zaideih-lyrics/3",
		exported: exportedAt,
		lyrics: lyrics.map((l) => ({ track: l.track, lang: l.lang ?? "", version: l.version, updated: l.updated_at, by: l.updated_by, hidden: l.hidden_at ? { at: l.hidden_at, by: l.hidden_by, reason: l.hidden_reason } : null })),
		versions: versions.map((v) => ({ track: v.track, lang: v.lang ?? "", version: v.version, text: v.text, by: v.member_id, at: v.at, note: v.note })),
		links: links.map((k) => ({ track: k.track, source: k.source, by: k.member_id, at: k.at, unlinked: k.unlinked_at ? { at: k.unlinked_at, by: k.unlinked_by } : null })),
		times: times.map((t) => ({ track: t.track, lang: t.lang ?? "", times: JSON.parse(t.times), by: t.member_id, at: t.at })),
	};
}

/** Tables that cannot be rebuilt from git: personal libraries (docs/library.md). */
export const LIBRARY_TABLES = Object.freeze(["members", "member_logins", "member_sessions", "uploads", "member_rights", "member_folders", "publish_requests", "published_tracks", "passkeys", "library_likes", "library_playlists", "lyrics", "lyrics_versions", "lyrics_reports", "lyrics_links", "lyrics_times", "lyrics_proposals", "album_holds", "album_hold_tracks", "album_hold_log", "songbooks", "songbook_members", "songbook_entries", "song_texts", "song_works", "song_people", "song_credits", "audio_versions", "audio_current", "audio_log", "library_shares"]);

/**
 * Why a reset must not go ahead, or null: it would lose personal libraries
 * (`counts`: rows per table) unless `dropLibrary` was chosen.
 */
export function libraryGuard(counts, dropLibrary) {
	const held = LIBRARY_TABLES.filter((t) => (counts[t] ?? 0) > 0);
	if (!held.length || dropLibrary) return null;
	return `${held.map((t) => `${t} holds ${counts[t]} row${counts[t] === 1 ? "" : "s"}`).join(" and ")}. Personal libraries cannot be rebuilt from git, and their files would stay in R2 (users/…) without an owner. Use "schema --apply" to add what is missing instead, or re-run with --drop-library to lose them.`;
}
